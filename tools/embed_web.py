# PlatformIO pre-build script: compresses web/index.html into src/web_index.h,
# so the page is part of the firmware (and of every firmware update).
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.path.join(project_dir, "web", "index.html")
target = os.path.join(project_dir, "src", "web_index.h")

with open(source, "rb") as f:
    html = f.read()
data = gzip.compress(html, compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")

header = (
    "// Generated by tools/embed_web.py from web/index.html, do not edit.\n"
    "#pragma once\n"
    "#include <Arduino.h>\n\n"
    "const size_t index_html_gz_len = %d;\n"
    "const uint8_t index_html_gz[] PROGMEM = {\n%s\n};\n" % (len(data), "\n".join(lines))
)

old = None
if os.path.exists(target):
    with open(target, "r") as f:
        old = f.read()
if old != header:
    with open(target, "w") as f:
        f.write(header)
print("embed_web: web/index.html %d bytes, gzip %d bytes" % (len(html), len(data)))

