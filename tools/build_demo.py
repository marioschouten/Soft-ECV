# Builds docs/demo.html: the web page of web/index.html with web/demo-mock.js in front of the page script,
# so the page runs in any browser with a simulated heating cycle instead of a D1.
# Called by tools/embed_web.py on every firmware build, or run it directly: python3 tools/build_demo.py
import os
import re


def build_demo(project_dir):
    with open(os.path.join(project_dir, "web", "index.html"), encoding="utf-8") as f:
        page = f.read()
    with open(os.path.join(project_dir, "web", "demo-mock.js"), encoding="utf-8") as f:
        mock = f.read()
    with open(os.path.join(project_dir, "src", "main.cpp"), encoding="utf-8") as f:
        version = re.search(r'FW_VERSION = "([^"]+)"', f.read()).group(1)

    mock = mock.replace("__FW_VERSION__", version)
    if "<script>" not in page:
        raise RuntimeError("web/index.html has no <script> to put the demo in front of")
    demo = page.replace("<script>", "<script>\n" + mock + "\n</script>\n<script>", 1)
    demo = re.sub(r"<title>(.*?)</title>", r"<title>\1 · demo</title>", demo, count=1)
    demo = "<!-- Generated by tools/build_demo.py from web/index.html and web/demo-mock.js, do not edit. -->\n" + demo

    target = os.path.join(project_dir, "docs", "demo.html")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    old = None
    if os.path.exists(target):
        with open(target, encoding="utf-8") as f:
            old = f.read()
    if old != demo:
        with open(target, "w", encoding="utf-8") as f:
            f.write(demo)
    return target, version


if __name__ == "__main__":
    path, fw = build_demo(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    print("build_demo: %s (firmware %s)" % (path, fw))
